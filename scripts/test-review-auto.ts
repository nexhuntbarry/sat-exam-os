// ── decide: confirm / undo a live fix (fake DB with app_settings) ──
function fakeDb(tables: Record<string, Record<string, unknown>[]>) {
  const writes: { table: string; op: string; v?: unknown }[] = [];
  const from = (table: string) => {
    const rows = (tables[table] ??= []);
    const filters: ((r: Record<string, unknown>) => boolean)[] = [];
    let patch: Record<string, unknown> | null = null;
    let del = false;
    let single = false;
    const run = () => {
      const hit = rows.filter((r) => filters.every((f) => f(r)));
      if (patch) {
        for (const r of hit) Object.assign(r, patch);
        writes.push({ table, op: "update", v: patch });
      }
      if (del) {
        for (const r of hit) rows.splice(rows.indexOf(r), 1);
        writes.push({ table, op: "delete" });
      }
      return { data: single ? (hit[0] ?? null) : hit.map((r) => ({ ...r })), error: null };
    };
    const b: Record<string, unknown> = {
      select: () => b,
      update: (u: Record<string, unknown>) => ((patch = u), b),
      delete: () => ((del = true), b),
      upsert: (v: Record<string, unknown>) => {
        const i = rows.findIndex((r) => r.key === v.key);
        if (i >= 0) rows[i] = v;
        else rows.push(v);
        writes.push({ table, op: "upsert", v });
        return Promise.resolve({ error: null });
      },
      eq: (k: string, v: unknown) => (filters.push((r) => r[k] === v), b),
      is: (k: string, v: unknown) => (filters.push((r) => (r[k] ?? null) === v), b),
      in: (k: string, v: unknown[]) => (filters.push((r) => v.includes(r[k])), b),
      maybeSingle: () => ((single = true), Promise.resolve(run())),
      then: (res: (x: unknown) => unknown, rej: (e: unknown) => unknown) => Promise.resolve(run()).then(res, rej),
    };
    return b;
  };
  return { db: { from } as unknown as SupabaseClient, writes, tables };
}

