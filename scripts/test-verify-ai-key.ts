// Unit checks for the AI-only key verification decision (lib/verify-ai-key.ts).
//   node --import tsx scripts/test-verify-ai-key.ts
import {
  AI_KEY_DISAGREE_PREFIX,
  AI_KEY_VERIFIED_PREFIX,
  aiKeyDisagreeNote,
  choiceValue,
  conditionHolds,
  decideVerification,
  isAiOnlyKeyNote,
  latexToExpr,
  mapValueToChoice,
  parseAiKeyDisagreeNote,
  type SolveCheck,
  type VerifyChecks,
  type VerifyRow,
} from "../lib/verify-ai-key";
import { splitNotes } from "../lib/explanation-autofix";
import { LIVE_FIX_TAG } from "../lib/live-questions";
import { TRUNCATION_NOTE } from "../lib/ai/solve-question";

let fail = 0;
const ok = (n: string, c: boolean, detail?: unknown) => {
  console.log(c ? "PASS" : "FAIL", n, detail !== undefined && !c ? JSON.stringify(detail) : "");
  if (!c) fail++;
};
const NOW = new Date("2026-11-07T12:00:00Z");

// ── Note format (shared with the review UI) ──────────────────────────
{
  const n = aiKeyDisagreeNote({ key: "B", ai: "C", value: "51.12", detail: "code C (51.12), plug-back of B fails (2*ans == 9), second solve C [verify-ai-key 2026-11-07]" });
  ok("note: example format", n.startsWith("Needs review: key says B, AI says C (51.12) — code C"), n);
  ok("note: one parsing_notes segment", splitNotes(n).length === 1 && splitNotes(`x; ${n}; y`)[1] === n);
  const p = parseAiKeyDisagreeNote(n);
  ok("note: round-trips", p?.key === "B" && p.ai === "C" && p.value === "51.12" && !!p.detail?.startsWith("code C"), p);
  const spr = parseAiKeyDisagreeNote(aiKeyDisagreeNote({ key: "6/13", ai: "6.8", value: null, detail: null }));
  ok("note: fill-in values, no value/detail", spr?.key === "6/13" && spr.ai === "6.8" && spr.value === null && spr.detail === null, spr);
  const semi = aiKeyDisagreeNote({ key: "A", ai: "D", value: null, detail: "x; y" });
  ok("note: ';' in detail can't split the note", !semi.includes(";"));
  ok("note: spec example parses", parseAiKeyDisagreeNote("Needs review: key says B, AI says C (51.12)")?.value === "51.12");
}

// ── Code helpers ─────────────────────────────────────────────────────
ok("latex: \\frac", choiceValue("$\\frac{3}{8}$") === 0.375);
ok("latex: nested \\frac / \\sqrt", Math.abs((choiceValue("$\\frac{\\sqrt{3}}{2}$") ?? 0) - Math.sqrt(3) / 2) < 1e-12);
ok("latex: 2\\sqrt{3} implicit ×", Math.abs((choiceValue("$2\\sqrt{3}$") ?? 0) - 2 * Math.sqrt(3)) < 1e-12);
ok("latex: thousands comma", choiceValue("5,500") === 5500);
ok("latex: negative / unicode minus", choiceValue("−8/3") === -8 / 3);
ok("latex: 2.5\\pi", Math.abs((choiceValue("$2.5\\pi$") ?? 0) - 2.5 * Math.PI) < 1e-12);
ok("latex: variables are not values", choiceValue("$y = 3x + 2$") === null && latexToExpr("x^2") === null);
ok("latex: words are not values", choiceValue("more general") === null);
ok("latex: mixed number 3\\frac{3}{5} = 3.6", choiceValue("$3\\frac{3}{5}$") === 3.6);
ok("latex: mixed number times 4", choiceValue("$2\\frac{1}{2} \\times 4$") === 10);
ok("latex: 1.5\\frac{1}{2} is not a mixed number", choiceValue("$1.5\\frac{1}{2}$") === 0.75);
const NUM = [{ label: "A", text: "5" }, { label: "B", text: "6" }, { label: "C", text: "$\\frac{28}{3}$" }, { label: "D", text: "8" }];
ok("map: exact value → choice", mapValueToChoice(28 / 3, NUM) === "C");
ok("map: no matching choice → null", mapValueToChoice(7, NUM) === null);
ok("map: printed-decimal tolerance (51.12 vs 51.1234)", mapValueToChoice(51.1234, [{ label: "A", text: "51.12" }, { label: "B", text: "52" }, { label: "C", text: "50" }, { label: "D", text: "49" }]) === "A");
ok("map: non-numeric choices → null", mapValueToChoice(3, [{ label: "A", text: "$x=3$" }, { label: "B", text: "4" }]) === null);
ok("cond: equation holds", conditionHolds("3*ans + 7 == 31", 8) === true);
ok("cond: equation fails", conditionHolds("3*ans + 7 == 31", 9) === false);
ok("cond: arithmetic only (no ans)", conditionHolds("2*1 + 3 == 5", null) === true);
ok("cond: inequality", conditionHolds("ans > 4", 5) === true && conditionHolds("ans <= 4", 5) === false);
ok("cond: unreadable → null", conditionHolds("the slope is 3", 3) === null);
ok("ai-only notes recognised", isAiOnlyKeyNote("Answer & explanation generated by AI solver — please verify") && isAiOnlyKeyNote("Solver self-contradicted (declared B, explained C)") && isAiOnlyKeyNote("Consensus solve NOT unanimous (5/5/6) — needs human"));
ok("other notes are not ai-only", !isAiOnlyKeyNote(TRUNCATION_NOTE) && !isAiOnlyKeyNote("Needs review: question text looks cut off — compare with the PDF."));

// ── Decision ─────────────────────────────────────────────────────────
const GOOD_EX = "The perpendicular slope is the negative reciprocal of 3/8, which is −8/3. Choice A is correct. Choices B, C and D are not negative reciprocals.";
const row = (o: Partial<VerifyRow> = {}): VerifyRow => ({
  id: "q1",
  module_id: "m1",
  original_question_number: 1,
  section: "Math",
  question_type: "Multiple Choice",
  question_text: "Line m has slope 3/8. What is the slope of a line perpendicular to m?",
  choices: [{ label: "A", text: "$-\\frac{8}{3}$" }, { label: "B", text: "$-\\frac{3}{8}$" }, { label: "C", text: "$\\frac{3}{8}$" }, { label: "D", text: "$\\frac{8}{3}$" }],
  correct_answer: "A",
  official_answer: null,
  explanation: GOOD_EX,
  parsing_status: "Needs Review",
  parsing_notes: "Answer & explanation generated by AI solver — please verify; Solver self-contradicted (declared A, explained D)",
  has_image: false,
  image_urls: [],
  has_table: false,
  ...o,
});
const s = (answer: string | null, extra: Partial<SolveCheck> = {}): SolveCheck => ({ answer, method: "t", problems: [], ...extra });
const math = (first: string | null, plug: "pass" | "fail" | "n/a", second: string | null, value: number | null = null): VerifyChecks => ({
  section: "Math",
  first: s(first, { value, mapped: true }),
  plugBack: { status: plug, detail: plug === "fail" ? "3*ans == 2" : "2 conditions" },
  second: s(second),
});

{
  const d = decideVerification(row(), math("A", "pass", "A", -8 / 3), false, NOW);
  ok("verified: all three agree", d.outcome === "verified", d);
  ok("verified: Needs Review with only AI-only-key notes → Approved", d.approved && d.update?.parsing_status === "Approved", d);
  const notes = String(d.update?.parsing_notes);
  ok("verified: AI-only-key notes cleared", !/generated by AI solver|self-contradicted/.test(notes), notes);
  ok("verified: verified note added", notes.includes(AI_KEY_VERIFIED_PREFIX), notes);
  ok("verified: key never written", !("correct_answer" in (d.update ?? {})) && !("official_answer" in (d.update ?? {})));
}
{
  const d = decideVerification(row({ parsing_notes: `Answer & explanation generated by AI solver — please verify; ${TRUNCATION_NOTE}` }), math("A", "pass", "A"), false, NOW);
  ok("verified but another blocking note → stays Needs Review", d.outcome === "verified" && !d.approved && !("parsing_status" in (d.update ?? {})) && d.blockers.length > 0, d);
  ok("…and that note is kept", String(d.update?.parsing_notes).includes(TRUNCATION_NOTE));
}
{
  const d = decideVerification(row({ question_text: "The following text is from Oscar Wilde's 1888 short story," }), math("A", "pass", "A"), false, NOW);
  ok("verified but findApproveBlocker (cut stem) → not approved", d.outcome === "verified" && !d.approved && d.blockers.some((b) => b.startsWith("approve check")), d.blockers);
}
{
  const d = decideVerification(row({ explanation: "The slope of the perpendicular line is 8/3. Choice D is correct." }), math("A", "pass", "A"), false, NOW);
  ok("explanation argues another choice → unverified, nothing written", d.outcome === "unverified" && d.update === null, d);
}
{
  const d = decideVerification(row(), math("A", "pass", "A"), true, NOW);
  ok("live test: verified Needs Review is NOT approved", d.outcome === "verified" && !d.approved && !("parsing_status" in (d.update ?? {})), d);
}
{
  const d = decideVerification(row(), math("C", "pass", "C", 0.375), false, NOW);
  ok("disagree: code + second say C", d.outcome === "disagree" && d.disagreement?.ai === "C", d);
  const note = splitNotes(String(d.update?.parsing_notes)).find((x) => x.startsWith(AI_KEY_DISAGREE_PREFIX)) ?? "";
  const p = parseAiKeyDisagreeNote(note);
  ok("disagree: structured note parses (key A, AI C, value 0.375)", p?.key === "A" && p.ai === "C" && p.value === "0.375", note);
  ok("disagree: Needs Review row stays Needs Review", d.update?.parsing_status === "Needs Review");
  ok("disagree: key never written", !("correct_answer" in (d.update ?? {})));
}
{
  const d = decideVerification(row(), math("A", "fail", "A"), false, NOW);
  ok("plug-back fails but both solves give the key → unverified, nothing written", d.outcome === "unverified" && d.update === null, d);
  const d2 = decideVerification(row(), math("A", "fail", null), false, NOW);
  ok("plug-back fails and only one solve answered → disagree (AI ?)", d2.outcome === "disagree" && d2.disagreement?.ai === "?", d2);
}
{
  const d = decideVerification(row({ parsing_status: "Approved", parsing_notes: null }), math("B", "pass", "A"), false, NOW);
  ok("Approved + disagreement: only a note, never demoted", d.outcome === "disagree" && !("parsing_status" in (d.update ?? {})) && String(d.update?.parsing_notes).startsWith(AI_KEY_DISAGREE_PREFIX), d.update);
}
{
  const d = decideVerification(row({ parsing_status: "Approved", parsing_notes: "Answer & explanation verified — approved." }), math("B", "pass", "B"), true, NOW);
  ok("live Approved + disagreement: note + [live-fix], stays Approved", !("parsing_status" in (d.update ?? {})) && String(d.update?.parsing_notes).startsWith(LIVE_FIX_TAG) && String(d.update?.parsing_notes).includes(AI_KEY_DISAGREE_PREFIX), d.update);
}
{
  const d = decideVerification(row({ parsing_status: "Draft" }), math("B", "pass", "B"), true, NOW);
  ok("live non-Approved + disagreement: status kept", !("parsing_status" in (d.update ?? {})), d.update);
}
{
  const d = decideVerification(row({ parsing_status: "Approved", parsing_notes: "Answer & explanation generated by AI solver — please verify" }), math("A", "pass", "A"), false, NOW);
  ok("Approved + verified: stays Approved, notes cleaned", d.outcome === "verified" && !("parsing_status" in (d.update ?? {})) && !String(d.update?.parsing_notes).includes("generated by AI solver"), d.update);
}
ok("no answers at all → no-answer, nothing written", (() => { const d = decideVerification(row(), math(null, "n/a", null), false, NOW); return d.outcome === "no-answer" && d.update === null; })());
ok("plug-back n/a → unverified (not approved)", (() => { const d = decideVerification(row(), math("A", "n/a", "A"), false, NOW); return d.outcome === "unverified" && d.update === null; })());
ok("second solve missing → unverified", (() => { const d = decideVerification(row(), math("A", "pass", null), false, NOW); return d.outcome === "unverified"; })());
{
  // Re-run: old verify notes replaced, not stacked.
  const first = decideVerification(row(), math("C", "pass", "C"), false, NOW);
  const again = decideVerification(row({ parsing_notes: String(first.update?.parsing_notes) }), math("C", "pass", "C"), false, NOW);
  ok("re-run replaces the old disagreement note", splitNotes(String(again.update?.parsing_notes)).filter((x) => x.startsWith(AI_KEY_DISAGREE_PREFIX)).length === 1);
}

// Fill-in: values compare by grading rules; rounding.
{
  const spr = row({
    question_type: "Student Produced Response",
    question_text: "What is the area, to the nearest tenth?",
    choices: [],
    correct_answer: "6.8",
    explanation: "The area is 6π − 12 ≈ 6.85, so to the nearest tenth it is 6.8.\n\nFinal answer: 6.8",
  });
  const agree = decideVerification(spr, { section: "Math", first: s("6.8", { value: 6.84955592 }), plugBack: { status: "pass", detail: "1" }, second: s("6.8") }, false, NOW);
  ok("fill-in: 6.8 agrees → verified", agree.outcome === "verified", agree);
  const dis = decideVerification(spr, { section: "Math", first: s("6.9", { value: 6.91 }), plugBack: { status: "pass", detail: "1" }, second: s("6.8") }, false, NOW);
  const p = parseAiKeyDisagreeNote(splitNotes(String(dis.update?.parsing_notes)).find((x) => x.startsWith(AI_KEY_DISAGREE_PREFIX)) ?? "");
  ok("fill-in: disagreement note carries the computed value", dis.outcome === "disagree" && p?.ai === "6.9" && p.value === "6.91", p);
}

// Reading & Writing: two solves.
{
  const rw = row({ section: "Reading & Writing", question_text: "Which choice best states the main purpose of the text?", choices: [{ label: "A", text: "To argue" }, { label: "B", text: "To describe" }, { label: "C", text: "To compare" }, { label: "D", text: "To refute" }], correct_answer: "B", explanation: "The text describes the process step by step. Choice B is correct." });
  const both = decideVerification(rw, { section: "Reading & Writing", first: s("B"), plugBack: null, second: s("B") }, false, NOW);
  ok("R&W: two solves agree → verified + approved", both.outcome === "verified" && both.approved, both);
  const split = decideVerification(rw, { section: "Reading & Writing", first: s("B"), plugBack: null, second: s("D") }, false, NOW);
  ok("R&W: second solve differs → disagree", split.outcome === "disagree" && split.disagreement?.ai === "D", split);
}

console.log(fail === 0 ? "\nALL PASS" : `\n${fail} FAILED`);
process.exit(fail === 0 ? 0 : 1);
